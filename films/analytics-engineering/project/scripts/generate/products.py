"""Writes each data product's descriptor in the Open Data Product Standard, from the product's own file
(governance/4-data-products/<name>.yml) and the dbt models, and checks each enterprise contract against
the model it's for, so the two can't drift:

- governance/6-product-descriptors/<name>.yaml, generated: the product in the Open Data Product
  Standard 1.0.0: its owner, domain, status, purpose and usage, its output ports (one per model
  version; a canonical table's with its enterprise contract), its input ports (the other products'
  canonical tables it reads, each with its contract), its team and support, and who reads it;
- governance/5-data-contracts/<model>_v<version>.yaml, written by hand: the enterprise contract of
  each canonical table (a public model, the shared core every product is built on) in the Open Data
  Contract Standard 3.1.0. Data governance's information architect writes it first; the data team
  builds the model to it. Only canonical tables have one: every other model, mart and dbt contract is
  the data team's, so changing it doesn't wait on governance. This script doesn't write them. It
  fails if a canonical table in a product has none, if a contract names no canonical table, or if a
  model differs from its contract: a column missing or extra, its type, whether it's required, its
  class, the primary key, the version, whether it's deprecated, the domain or the product. Then data
  governance looks at how the change got there: a contract changes first, never after the code.

Both standards are Bitol's, at the Linux Foundation. Contract standard 3.1.0 is the version Ontos
reads and writes; their JSON schemas are kept in governance/7-standards/ (README there, with the
newer versions). The descriptors carry the consumers too: the exposures and the other products that
read each output.

It reads target/manifest.json (dbt parse first). It fails if a public model or mart is in no
product, or in two; if an owner can't be reached (governance/2-owners/owners.yml); or if a file
doesn't validate against its schema.

    python scripts/generate/products.py           # write the product descriptors, and check the contracts
    python scripts/generate/products.py --check   # also fail if a descriptor is out of date
"""
import argparse
import json
import sys
import uuid
from pathlib import Path

import jsonschema
import yaml

ROOT = Path(__file__).resolve().parents[2]
GOVERNANCE = ROOT / "governance"
PRODUCTS = GOVERNANCE / "4-data-products"
FOLDERS = {"odcs": GOVERNANCE / "5-data-contracts", "odps": GOVERNANCE / "6-product-descriptors"}
MANIFEST = ROOT / "target" / "manifest.json"
REGISTER = GOVERNANCE / "2-owners" / "owners.yml"
ODCS, ODPS = "v3.1.0", "v1.0.0"
SCHEMAS = {"odcs": GOVERNANCE / "7-standards" / "open-data-contract-standard-3.1.0.schema.json",
           "odps": GOVERNANCE / "7-standards" / "open-data-product-standard-1.0.0.schema.json"}
NAMESPACE = uuid.uuid5(uuid.NAMESPACE_DNS, "uni.example")
LOGICAL = {"string": "string", "int": "integer", "integer": "integer", "bigint": "integer", "date": "date",
           "timestamp": "timestamp", "boolean": "boolean", "decimal": "number", "numeric": "number", "double": "number"}
HEADER = ("# Generated by scripts/generate/products.py from {source} and the dbt models. Don't edit it:\n"
          "# change those, then run the script. CI fails if it's out of date.\n")
CONTRACTS = FOLDERS["odcs"]


def stable_id(*parts):
    """The same id every time for the same thing, so a descriptor keeps its id across builds."""
    return str(uuid.uuid5(NAMESPACE, "/".join(parts)))


def port_name(node):
    return node["name"] + (f"_v{node['version']}" if node.get("version") is not None else "")


def semver(node):
    return f"{node['version'] if node.get('version') is not None else 1}.0.0"


def canonical(node):
    """A canonical table: a public model, the shared core every product is built on. Only these have an
    enterprise contract."""
    return node["resource_type"] == "model" and node.get("access") == "public"


def team(owner, emails):
    return {"name": owner, "members": [{"username": emails[owner], "name": owner, "role": "owner"}]}


def promised(node, product):
    """What the model says that its enterprise contract must say too: the table's name, version, status,
    domain and product, and each column's type, whether it's required, its class and the primary key."""
    pk = next((c["columns"] for c in node.get("constraints", []) if c["type"] == "primary_key"), [])
    columns = {}
    for col, spec in node["columns"].items():
        columns[col] = {"logicalType": LOGICAL.get(str(spec.get("data_type")).lower(), "string"),
                        "physicalType": spec.get("data_type"),
                        "required": any(c["type"] == "not_null" for c in spec.get("constraints", [])),
                        "classification": (spec.get("meta") or {}).get("personal_data"),
                        "primaryKey": col in pk,
                        "primaryKeyPosition": pk.index(col) + 1 if col in pk else None}
    return {"name": port_name(node), "version": semver(node), "deprecated": bool(node.get("deprecation_date")),
            "domain": product["domain"], "dataProduct": product["name"], "physicalName": node["alias"],
            "columns": columns}


def shown(value):
    """A value as the YAML says it: true, false, none."""
    return {True: "true", False: "false", None: "none"}.get(value, value) if not isinstance(value, int) or isinstance(value, bool) else value


def differences(contract, expected):
    """Where an enterprise contract and its model differ, each as one line."""
    found = []
    for key in ("name", "version", "domain", "dataProduct"):
        if contract.get(key) != expected[key]:
            found.append(f"{key}: {contract.get(key)!r} in the contract, {expected[key]!r} in the model")
    if (contract.get("status") == "deprecated") != expected["deprecated"]:
        found.append(f"status: {contract.get('status')!r} in the contract, but the model "
                     + ("has a deprecation date" if expected["deprecated"] else "has no deprecation date"))
    table = next((o for o in contract.get("schema", []) if o.get("name") == expected["name"]), None)
    if table is None:
        return found + [f"no schema object named {expected['name']}"]
    if table.get("physicalName") != expected["physicalName"]:
        found.append(f"physicalName: {table.get('physicalName')!r} in the contract, {expected['physicalName']!r} in the model")
    written = {prop["name"]: prop for prop in table.get("properties", [])}
    for col in expected["columns"]:
        if col not in written:
            found.append(f"{col}: in the model, not in the contract")
    for col, prop in written.items():
        model = expected["columns"].get(col)
        if model is None:
            found.append(f"{col}: in the contract, not in the model")
            continue
        for key, value in model.items():
            have = prop.get(key, False if key in ("required", "primaryKey") else None)
            if have != value:
                found.append(f"{col}: {key}: {shown(have)} in the contract, {shown(value)} in the model")
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="also fail if a descriptor is out of date")
    args = parser.parse_args()
    if not MANIFEST.exists():
        raise SystemExit("target/manifest.json is missing: run dbt parse --profiles-dir . first")
    manifest = json.loads(MANIFEST.read_text())
    nodes = manifest["nodes"]
    emails = {o["name"]: o["email"] for o in (yaml.safe_load(REGISTER.read_text()) or {})["owners"]}
    schemas = {key: json.loads(path.read_text()) for key, path in SCHEMAS.items()}
    products = [(path, yaml.safe_load(path.read_text())) for path in sorted(PRODUCTS.glob("*.yml"))]
    problems = []

    # Which product each model version is an output of.
    by_model = {}
    for model in nodes.values():
        if model["resource_type"] == "model":
            by_model.setdefault((model["name"], model.get("version")), model)
    output_of = {}
    for path, product in products:
        if product["owner"] not in emails:
            problems.append(f"{path.relative_to(ROOT)}: owner {product['owner']!r} isn't in {REGISTER.relative_to(ROOT)}")
        for out in product["outputs"]:
            node = by_model.get((out["model"], out.get("version")))
            if not node:
                problems.append(f"{path.relative_to(ROOT)}: no model {out['model']} version {out.get('version')}")
            elif node["unique_id"] in output_of:
                problems.append(f"{node['unique_id']} is an output of {output_of[node['unique_id']]} and {product['name']}")
            else:
                output_of[node["unique_id"]] = product["name"]
    for node in nodes.values():
        shared = node["resource_type"] == "model" and (
            node.get("access") == "public" or node["original_file_path"].startswith("models/marts/"))
        if shared and node["unique_id"] not in output_of:
            problems.append(f"{port_name(node)} is shared but in no product: add it to a product's outputs in {PRODUCTS.relative_to(ROOT)}/")
    if problems:
        raise SystemExit("\n".join(problems))

    # The enterprise contracts: one for each canonical table, written by data governance; none for anything else.
    product_of = {product["name"]: product for _, product in products}
    contracts, drifted, invalid = {}, [], []
    for path in sorted(CONTRACTS.glob("*.yaml")):
        contract = yaml.safe_load(path.read_text())
        node = next((n for uid, n in nodes.items() if uid in output_of and port_name(n) == contract.get("name")), None)
        if node is None or not canonical(node):
            drifted.append(f"{path.relative_to(ROOT)}: {contract.get('name')} isn't a canonical table in a product, "
                           "and only canonical tables have an enterprise contract")
            continue
        contracts[node["unique_id"]] = contract
        try:
            jsonschema.validate(contract, schemas["odcs"])
        except jsonschema.ValidationError as error:
            invalid.append(f"{path.relative_to(ROOT)}: {error.message} at {'/'.join(map(str, error.absolute_path))}")
        found = differences(contract, promised(node, product_of[output_of[node["unique_id"]]]))
        if found:
            drifted.append(f"{port_name(node)} differs from its enterprise contract, {path.relative_to(ROOT)}:")
            drifted.extend("  " + line for line in found)
    for uid, name in output_of.items():
        if canonical(nodes[uid]) and uid not in contracts:
            drifted.append(f"{port_name(nodes[uid])} is canonical but has no enterprise contract: data governance's "
                           f"information architect writes it first, in {CONTRACTS.relative_to(ROOT)}/")

    def readers(uid):
        """The exposures and other products that read a model."""
        found = set()
        for child in manifest["child_map"].get(uid, []):
            if child.startswith("exposure."):
                found.add(f"exposure {manifest['exposures'][child]['name']}")
            elif child in output_of and output_of[child] != output_of[uid]:
                found.add(f"product {output_of[child]}")
        return sorted(found)

    files = {}
    for path, product in products:
        name, owner = product["name"], product["owner"]
        output_ports, input_ports = [], {}
        for out in product["outputs"]:
            node = by_model[(out["model"], out.get("version"))]
            first = " ".join(node["description"].split()).split(". ")[0].rstrip(".") + "."
            port = {"name": port_name(node), "description": first, "type": "table", "version": semver(node)}
            if node["unique_id"] in contracts:
                port["contractId"] = contracts[node["unique_id"]]["id"]
            if node.get("deprecation_date"):
                port["description"] = f"Deprecated: removed after {str(node['deprecation_date'])[:10]}. " + port["description"]
            output_ports.append(port)
            for parent in node["depends_on"]["nodes"]:
                if parent in output_of and output_of[parent] != name and parent in contracts:
                    pnode = nodes[parent]
                    input_ports[parent] = {"name": port_name(pnode), "version": semver(pnode),
                                           "contractId": contracts[parent]["id"]}
        consumers = sorted({r for out in product["outputs"]
                            for r in readers(by_model[(out["model"], out.get("version"))]["unique_id"])})
        descriptor = {"apiVersion": ODPS, "kind": "DataProduct", "id": stable_id("odps", name), "name": product["title"],
                      "version": product["version"], "status": product["status"], "domain": product["domain"],
                      "description": {"purpose": " ".join(product["description"]["purpose"].split()),
                                      "usage": " ".join(product["description"]["usage"].split())},
                      **({"inputPorts": list(input_ports.values())} if input_ports else {}),
                      "outputPorts": output_ports, "team": team(owner, emails), "support": product["support"],
                      "customProperties": [{"property": "consumers", "value": consumers}]}
        files[FOLDERS["odps"] / f"{name}.yaml"] = (descriptor, path)

    stale = []
    for target, (document, source) in sorted(files.items()):
        try:
            jsonschema.validate(json.loads(json.dumps(document)), schemas["odps"])
        except jsonschema.ValidationError as error:
            invalid.append(f"{target.relative_to(ROOT)}: {error.message} at {'/'.join(map(str, error.absolute_path))}")
        text = HEADER.format(source=source.relative_to(ROOT)) + yaml.safe_dump(document, sort_keys=False, width=100, allow_unicode=True)
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(exist_ok=True)
            target.write_text(text)
    for extra in sorted(FOLDERS["odps"].glob("*.yaml")):
        if extra not in files:
            stale.append(f"{extra.relative_to(ROOT)} (no product has it)")
            if not args.check:
                extra.unlink()
    if invalid:
        raise SystemExit("not valid against its schema:\n" + "\n".join(invalid))
    if drifted:
        print("\n".join(drifted) + "\nThe contract comes first: data governance's information architect changes it, "
              "then the data team builds to it.", file=sys.stderr)
        sys.exit(1)
    if args.check and stale:
        print("out of date: run python scripts/generate/products.py\n" + "\n".join(stale), file=sys.stderr)
        sys.exit(1)
    print(f"{len(files)} products {'are up to date and valid' if args.check else 'written, and valid'} "
          f"(product standard {ODPS}),\n{len(contracts)} enterprise contracts match their models (contract standard {ODCS})")


if __name__ == "__main__":
    main()

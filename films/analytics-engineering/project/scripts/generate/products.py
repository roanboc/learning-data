"""Writes each data product's descriptor in the open standards, from the product's own file
(products/<name>.yml) and the dbt contracts, so the two can't drift:

- products/odps/<name>.odps.yaml: the product in ODPS v1.0.0 (Open Data Product Standard): its
  owner, domain, status, purpose and usage, its output ports (one per model version, each with its
  contract), its input ports (the other products' contracts it reads), its team and support;
- products/odcs/<model>_v<version>.odcs.yaml: one contract per output port in ODCS v3.1.0 (Open Data
  Contract Standard), generated from the model's YAML: each column with its type, whether it's
  required, the primary key, its class (meta.personal_data), its description and its tests as
  quality rules (with their dimension: ODCS calls validity "conformity"); the known limitations;
  the product's service levels, team and support.

Both standards are Bitol's, at the Linux Foundation. ODCS v3.1.0 is the version Ontos reads and
writes; their JSON schemas are kept in products/schemas/ (README there, with the newer versions). The descriptors carry the
consumers too: the exposures and the other products that read each output.

It reads target/manifest.json (dbt parse first). It fails if a public model or mart is in no
product, or in two; if an owner can't be reached (models/_shared/_shared__owners.yml); or if a file
it writes doesn't validate against its schema.

    python scripts/generate/products.py           # write products/odps/ and products/odcs/
    python scripts/generate/products.py --check   # fail if any is out of date, or invalid
"""
import argparse
import json
import sys
import uuid
from pathlib import Path

import jsonschema
import yaml

ROOT = Path(__file__).resolve().parents[2]
PRODUCTS = ROOT / "products"
MANIFEST = ROOT / "target" / "manifest.json"
REGISTER = ROOT / "models" / "_shared" / "_shared__owners.yml"
ODCS, ODPS = "v3.1.0", "v1.0.0"
SCHEMAS = {"odcs": PRODUCTS / "schemas" / "odcs-json-schema-v3.1.0.json",
           "odps": PRODUCTS / "schemas" / "odps-json-schema-v1.0.0.json"}
NAMESPACE = uuid.uuid5(uuid.NAMESPACE_DNS, "uni.example")
LOGICAL = {"string": "string", "int": "integer", "integer": "integer", "bigint": "integer", "date": "date",
           "timestamp": "timestamp", "boolean": "boolean", "decimal": "number", "numeric": "number", "double": "number"}
HEADER = ("# Generated by scripts/generate/products.py from {source} and the dbt contracts. Don't edit it:\n"
          "# change those, then run the script. CI fails if it's out of date.\n")


def stable_id(*parts):
    """The same id every time for the same thing, so a contract keeps its id across builds."""
    return str(uuid.uuid5(NAMESPACE, "/".join(parts)))


def port_name(node):
    return node["name"] + (f"_v{node['version']}" if node.get("version") is not None else "")


def semver(node):
    return f"{node['version'] if node.get('version') is not None else 1}.0.0"


def quality(test):
    """A dbt test as an ODCS quality rule: the library's metric where one fits, else the dbt test itself."""
    kind = (test.get("test_metadata") or {}).get("name", "singular")
    kwargs = (test.get("test_metadata") or {}).get("kwargs", {})
    rule = {"id": test["name"][:120]}
    if kind == "not_null":
        rule.update(metric="nullValues", mustBe=0, unit="rows")
    elif kind == "unique":
        rule.update(metric="duplicateValues", mustBe=0, unit="rows")
    elif kind == "accepted_values":
        rule.update(metric="invalidValues", mustBe=0, unit="rows", arguments={"validValues": kwargs.get("values")})
    else:
        rule.update(type="custom", engine="dbt", implementation=f"{kind}: {test['name']}")
    meta = test.get("meta") or {}
    # ODCS names DAMA's validity "conformity"; the other five are the same words.
    rule["dimension"] = {"validity": "conformity"}.get(meta.get("dimension"), meta.get("dimension"))
    rule["severity"] = test["config"].get("severity", "error").lower()
    if test.get("description"):
        rule["description"] = " ".join(test["description"].split())
    return rule


def team(owner, emails):
    return {"name": owner, "members": [{"username": emails[owner], "name": owner, "role": "owner"}]}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated file is out of date or invalid")
    args = parser.parse_args()
    if not MANIFEST.exists():
        raise SystemExit("target/manifest.json is missing: run dbt parse --profiles-dir . first")
    manifest = json.loads(MANIFEST.read_text())
    nodes = manifest["nodes"]
    emails = {o["name"]: o["email"] for o in (yaml.safe_load(REGISTER.read_text()) or {})["owners"]}
    schemas = {key: json.loads(path.read_text()) for key, path in SCHEMAS.items()}
    products = [(path, yaml.safe_load(path.read_text())) for path in sorted(PRODUCTS.glob("*.yml"))]
    problems = []

    # Which product each model version is an output of.
    by_model = {}
    for model in nodes.values():
        if model["resource_type"] == "model":
            by_model.setdefault((model["name"], model.get("version")), model)
    output_of = {}
    for path, product in products:
        if product["owner"] not in emails:
            problems.append(f"{path.relative_to(ROOT)}: owner {product['owner']!r} isn't in {REGISTER.relative_to(ROOT)}")
        for out in product["outputs"]:
            node = by_model.get((out["model"], out.get("version")))
            if not node:
                problems.append(f"{path.relative_to(ROOT)}: no model {out['model']} version {out.get('version')}")
            elif node["unique_id"] in output_of:
                problems.append(f"{node['unique_id']} is an output of {output_of[node['unique_id']]} and {product['name']}")
            else:
                output_of[node["unique_id"]] = product["name"]
    for node in nodes.values():
        shared = node["resource_type"] == "model" and (
            node.get("access") == "public" or node["original_file_path"].startswith("models/marts/"))
        if shared and node["unique_id"] not in output_of:
            problems.append(f"{port_name(node)} is shared but in no product: add it to a product's outputs in products/")
    if problems:
        raise SystemExit("\n".join(problems))

    def readers(uid):
        """The exposures and other products that read a model."""
        found = set()
        for child in manifest["child_map"].get(uid, []):
            if child.startswith("exposure."):
                found.add(f"exposure {manifest['exposures'][child]['name']}")
            elif child in output_of and output_of[child] != output_of[uid]:
                found.add(f"product {output_of[child]}")
        return sorted(found)

    files = {}
    for path, product in products:
        name, owner = product["name"], product["owner"]
        output_ports, input_ports = [], {}
        for out in product["outputs"]:
            node = by_model[(out["model"], out.get("version"))]
            contract_id = stable_id("odcs", port_name(node))
            deprecated = node.get("deprecation_date")
            status = "deprecated" if deprecated else product["status"]
            meta = node.get("meta") or {}
            columns = node["columns"]
            pk = next((c["columns"] for c in node.get("constraints", []) if c["type"] == "primary_key"), [])
            tests = [t for t in nodes.values() if t["resource_type"] == "test" and t.get("attached_node") == node["unique_id"]]
            properties = []
            for col, spec in columns.items():
                prop = {"name": col, "logicalType": LOGICAL.get(str(spec.get("data_type")).lower(), "string"),
                        "physicalType": spec.get("data_type"),
                        "required": any(c["type"] == "not_null" for c in spec.get("constraints", [])),
                        "classification": spec["meta"].get("personal_data")}
                if col in pk:
                    prop.update(primaryKey=True, primaryKeyPosition=pk.index(col) + 1)
                if spec.get("description"):
                    prop["description"] = " ".join(spec["description"].split())
                rules = [quality(t) for t in tests if t.get("column_name") == col]
                if rules:
                    prop["quality"] = rules
                properties.append(prop)
            schema_object = {"name": port_name(node), "physicalName": node["alias"], "logicalType": "object",
                             "physicalType": "table", "description": " ".join(node["description"].split()),
                             "properties": properties}
            object_rules = [quality(t) for t in tests if not t.get("column_name")]
            if object_rules:
                schema_object["quality"] = object_rules
            limitations = " ".join(f"{lim['id']}: {' '.join(lim['text'].split())}" for lim in meta.get("limitations", []))
            contract = {
                "apiVersion": ODCS, "kind": "DataContract", "id": contract_id, "name": port_name(node),
                "version": semver(node), "status": status, "domain": product["domain"], "dataProduct": name,
                "description": {k: v for k, v in {"purpose": " ".join(product["description"]["purpose"].split()),
                                                  "usage": " ".join(product["description"]["usage"].split()),
                                                  "limitations": limitations or None}.items() if v},
                "schema": [schema_object],
                "slaProperties": [{k: v for k, v in sla.items()} for sla in product.get("service_levels", [])],
                "team": team(owner, emails),
                "support": product["support"],
                "customProperties": [{"property": "grain", "value": meta.get("grain")},
                                     {"property": "dbtModel", "value": port_name(node)},
                                     {"property": "consumers", "value": readers(node["unique_id"])}]
                                    + ([{"property": "deprecationDate", "value": str(deprecated)[:10]}] if deprecated else []),
            }
            files[PRODUCTS / "odcs" / f"{port_name(node)}.odcs.yaml"] = ("odcs", contract, path)
            first = " ".join(node["description"].split()).split(". ")[0].rstrip(".") + "."
            port = {"name": port_name(node), "description": first,
                    "type": "table", "version": semver(node), "contractId": contract_id}
            if deprecated:
                port["description"] = f"Deprecated: removed after {str(deprecated)[:10]}. " + port["description"]
            output_ports.append(port)
            for parent in node["depends_on"]["nodes"]:
                if parent in output_of and output_of[parent] != name:
                    pnode = nodes[parent]
                    input_ports[parent] = {"name": port_name(pnode), "version": semver(pnode),
                                           "contractId": stable_id("odcs", port_name(pnode))}
        consumers = sorted({r for out in product["outputs"]
                            for r in readers(by_model[(out["model"], out.get("version"))]["unique_id"])})
        descriptor = {"apiVersion": ODPS, "kind": "DataProduct", "id": stable_id("odps", name), "name": product["title"],
                      "version": product["version"], "status": product["status"], "domain": product["domain"],
                      "description": {"purpose": " ".join(product["description"]["purpose"].split()),
                                      "usage": " ".join(product["description"]["usage"].split())},
                      **({"inputPorts": list(input_ports.values())} if input_ports else {}),
                      "outputPorts": output_ports, "team": team(owner, emails), "support": product["support"],
                      "customProperties": [{"property": "consumers", "value": consumers}]}
        files[PRODUCTS / "odps" / f"{name}.odps.yaml"] = ("odps", descriptor, path)

    stale, invalid = [], []
    for target, (kind, document, source) in sorted(files.items()):
        try:
            jsonschema.validate(json.loads(json.dumps(document)), schemas[kind])
        except jsonschema.ValidationError as error:
            invalid.append(f"{target.relative_to(ROOT)}: {error.message} at {'/'.join(map(str, error.absolute_path))}")
        text = HEADER.format(source=source.relative_to(ROOT)) + yaml.safe_dump(document, sort_keys=False, width=100, allow_unicode=True)
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(exist_ok=True)
            target.write_text(text)
    for folder in ("odcs", "odps"):
        for extra in sorted((PRODUCTS / folder).glob("*.yaml")) if (PRODUCTS / folder).exists() else []:
            if extra not in files:
                stale.append(f"{extra.relative_to(ROOT)} (no product has it)")
                if not args.check:
                    extra.unlink()
    if invalid:
        raise SystemExit("not valid against its schema:\n" + "\n".join(invalid))
    if args.check and stale:
        print("out of date: run python scripts/generate/products.py\n" + "\n".join(stale), file=sys.stderr)
        sys.exit(1)
    print(f"{len(files)} files {'are up to date and valid' if args.check else 'written, and valid'}: "
          f"{sum(1 for k, _, _ in files.values() if k == 'odps')} products (ODPS {ODPS}), "
          f"{sum(1 for k, _, _ in files.values() if k == 'odcs')} contracts (ODCS {ODCS})")


if __name__ == "__main__":
    main()

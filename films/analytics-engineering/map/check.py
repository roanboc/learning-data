"""Checks the governance part of Noor's map, and writes its views from it.

Each element is one YAML file (README.md). The check fails if:

- a file's id isn't its file name, or its prefix doesn't fit its kind and folder;
- an element has no name, owner or status, or its owner can't be reached (the project's
  models/_shared/_shared__owners.yml);
- a relationship names an element that isn't on the map, names it wrongly, or joins two kinds the
  map doesn't join that way;
- a business object hasn't exactly one home, or a copy isn't synced one way from the home (through
  other copies, with no loop), or has no drift check;
- a capability is coloured with no evidence, a service has no promise or no way to ask, or realizes
  no capability.

It writes two views, so nobody draws them by hand:

- views/services.md: what governance must be able to do, and the services it offers, with their
  promises and the steps that keep each promise;
- views/responsibilities.md: who does each step, who answers for it and who's told, from the steps.

    python check.py           # check the map and write its views
    python check.py --check   # check the map, and fail if a view is out of date
"""
import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
REGISTER = ROOT.parent / "project" / "models" / "_shared" / "_shared__owners.yml"
VIEWS = ROOT / "views"
KINDS = {"CAP": ("strategy", "capability"), "SRV": ("business", "business service"),
         "ROL": ("business", "business role"), "ACT": ("business", "business actor"),
         "STP": ("business", "business process"), "OBJ": ("information", "business object"),
         "APP": ("application", "application component"), "PRN": ("motivation", "principle")}
# Which relationship joins which kinds: from the element that holds it to the one it names.
JOINS = {"composition": {("CAP", "CAP")},
         "realization": {("SRV", "CAP"), ("STP", "SRV")},
         "assignment": {("ACT", "ROL"), ("STP", "ROL"), ("APP", "ROL")},
         "access (reads)": {("STP", "OBJ")},
         "access (writes)": {("STP", "OBJ")},
         "triggering": {("STP", "STP")}}
STATUSES = {"confirmed", "draft", "proposed"}
HEADER = "*Generated by `check.py` from the map's elements. Don't edit it: change the elements, then run it.*\n"


def ref(text):
    """'ROL-003 · data steward' as ('ROL-003', 'data steward'); a bare id has no name."""
    ident, _, name = str(text).partition(" · ")
    return ident.strip(), name.strip() or None


def load():
    elements, problems = {}, []
    for path in sorted(ROOT.glob("*/*.yml")):
        if path.parent.name == "views":
            continue
        element = yaml.safe_load(path.read_text()) or {}
        where = path.relative_to(ROOT)
        ident = element.get("id")
        if ident != path.stem:
            problems.append(f"{where}: id {ident!r} isn't the file's name")
            continue
        folder, kind = KINDS.get(ident.split("-")[0], (None, None))
        if (folder, kind) != (path.parent.name, element.get("kind")):
            problems.append(f"{where}: a {ident.split('-')[0]} is a {kind}, in {folder}/")
        for key in ("name", "owner", "status"):
            if not element.get(key):
                problems.append(f"{where}: no {key}")
        if element.get("status") and element["status"] not in STATUSES:
            problems.append(f"{where}: status {element['status']!r} isn't one of {', '.join(sorted(STATUSES))}")
        element["_path"] = where
        elements[ident] = element
    return elements, problems


def check(elements, owners):
    problems = []

    def target(where, text, prefixes):
        ident, name = ref(text)
        found = elements.get(ident)
        if not found:
            problems.append(f"{where}: {ident} isn't on the map")
        elif name and name != found["name"]:
            problems.append(f"{where}: {ident} is {found['name']!r}, not {name!r}")
        elif ident.split("-")[0] not in prefixes:
            problems.append(f"{where}: {ident} is a {found['kind']}")
        return ident if found else None

    for ident, element in elements.items():
        where, prefix = element["_path"], ident.split("-")[0]
        if element.get("owner") and element["owner"] not in owners:
            problems.append(f"{where}: owner {element['owner']!r} isn't in {REGISTER.relative_to(ROOT.parent)}")
        for rel in element.get("relationships") or []:
            (kind, text), = rel.items()
            allowed = {b for a, b in JOINS.get(kind, set()) if a == prefix}
            if not allowed:
                problems.append(f"{where}: a {element['kind']} has no {kind} relationship")
                continue
            target(where, text, allowed)
        if prefix == "CAP" and element.get("heat") and not element.get("evidence"):
            problems.append(f"{where}: coloured {element['heat']} with no evidence")
        if prefix == "SRV":
            for key in ("promise", "how_to_ask"):
                if not element.get(key):
                    problems.append(f"{where}: a service with no {key.replace('_', ' ')}")
            if not any("realization" in rel for rel in element.get("relationships") or []):
                problems.append(f"{where}: realizes no capability")
        if prefix == "OBJ":
            home = target(where, element.get("home", "none"), {"APP"}) if element.get("home") else None
            if not home:
                problems.append(f"{where}: no home")
                continue
            synced = {home: None}
            for copy in element.get("copies") or []:
                place = target(where, copy.get("in", "none"), {"APP"})
                source = ref(copy.get("synced from", ""))[0]
                if place in synced:
                    problems.append(f"{where}: two homes or copies in {place}: one home, one copy per place")
                elif source not in synced:
                    problems.append(f"{where}: the copy in {place} is synced from {source or 'nowhere'}, "
                                    "which isn't the home or a copy before it")
                if str(copy.get("drift check")).lower() != "yes":
                    problems.append(f"{where}: the copy in {place} has no drift check")
                synced[place] = source
    return problems


def services_view(elements):
    def named(prefix):
        return [e for i, e in sorted(elements.items()) if i.startswith(prefix)]

    def rels(element, kind):
        return [ref(text)[0] for rel in element.get("relationships") or [] for k, text in rel.items() if k == kind]

    lines = ["# Governance: what it must do, and what it offers", "", HEADER,
             "## What it must be able to do", "", "| Capability | Owner | Heat | Evidence |", "|---|---|---|---|"]
    for cap in named("CAP"):
        lines.append(f"| {cap['id']} {cap['name']} | {cap['owner']} | {cap.get('heat', '')} | {cap.get('evidence', '')} |")
    lines += ["", "## The services it offers", ""]
    for srv in named("SRV"):
        caps = ", ".join(f"{c} {elements[c]['name']}" for c in rels(srv, "realization"))
        lines += [f"### {srv['id']} {srv['name']}", "", f"**Promise.** {' '.join(srv['promise'].split())}", "",
                  f"**How to ask.** {srv['how_to_ask'][0].upper() + srv['how_to_ask'][1:]}. **Owner:** {srv['owner']}. **Realizes:** {caps}.", ""]
        steps = [s for s in named("STP") if srv["id"] in rels(s, "realization")]
        if steps:
            lines += ["| Step | Who does it | Reads | Writes | Then |", "|---|---|---|---|---|"]
            for step in ordered(steps, rels):
                cell = lambda kind: ", ".join(f"{i} {elements[i]['name']}" for i in rels(step, kind))
                lines.append(f"| {step['id']} {step['name']} | {cell('assignment')} | {cell('access (reads)')} "
                             f"| {cell('access (writes)')} | {cell('triggering')} |")
            lines.append("")
        else:
            lines += ["Its steps aren't on the map yet.", ""]
    return "\n".join(lines).rstrip() + "\n"


def ordered(steps, rels):
    """The steps in the order they trigger each other, from the one nothing triggers."""
    ids = {s["id"]: s for s in steps}
    triggered = {t for s in steps for t in rels(s, "triggering")}
    out, todo = [], [s for s in steps if s["id"] not in triggered]
    while todo:
        step = todo.pop(0)
        if step in out:
            continue
        out.append(step)
        todo += [ids[t] for t in rels(step, "triggering") if t in ids]
    return out + [s for s in steps if s not in out]


def responsibilities_view(elements):
    """From the steps: who does it (the role assigned), who answers for it (the role of the actor who
    owns what it writes) and who's told (the roles of the steps that read what it writes)."""
    def rels(element, kind):
        return [ref(text)[0] for rel in element.get("relationships") or [] for k, text in rel.items() if k == kind]

    roles_of = {}
    for actor in (e for i, e in elements.items() if i.startswith("ACT")):
        for owner in [o for o in {e["owner"] for e in elements.values()} if o.split(",")[0] == actor["name"]]:
            roles_of.setdefault(owner, rels(actor, "assignment"))
    steps = [e for i, e in sorted(elements.items()) if i.startswith("STP")]
    roles = sorted({r for s in steps for r in rels(s, "assignment")})
    table = {}
    for step in ordered(steps, rels):
        row = {r: set() for r in roles}
        for r in rels(step, "assignment"):
            row[r].add("does")
        for obj in rels(step, "access (writes)"):
            for r in roles_of.get(elements[obj]["owner"], []):
                row.setdefault(r, set()).add("answers")
            for other in steps:
                if other is not step and obj in rels(other, "access (reads)"):
                    for r in rels(other, "assignment"):
                        row.setdefault(r, set()).add("told")
        table[step["id"]] = row
    roles = sorted({r for row in table.values() for r, marks in row.items() if marks})
    lines = ["# Governance: who does what", "", HEADER,
             "From the steps on the map: who **does** each step (the role assigned to it), who **answers** for it "
             "(the role of the person who owns what it writes) and who's **told** (the roles of the steps that "
             "read what it writes). Who's consulted isn't on the map: it's agreed in each step.", "",
             "| Step | " + " | ".join(f"{r} {elements[r]['name']}" for r in roles) + " |",
             "|---|" + "---|" * len(roles)]
    for ident, row in table.items():
        lines.append(f"| {ident} {elements[ident]['name']} | "
                     + " | ".join(", ".join(m for m in ("does", "answers", "told") if m in row.get(r, ())) for r in roles) + " |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a view is out of date")
    args = parser.parse_args()
    register = yaml.safe_load(REGISTER.read_text()) or {}
    owners = {o["name"] for o in register["owners"]} | {r["name"] for r in register["reviewers"].values()}
    elements, problems = load()
    problems += check(elements, owners)
    if problems:
        raise SystemExit("the map has problems:\n" + "\n".join(problems))
    views = {VIEWS / "services.md": services_view(elements), VIEWS / "responsibilities.md": responsibilities_view(elements)}
    stale = [p for p, text in views.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale:
            print("out of date: run python check.py\n" + "\n".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            sys.exit(1)
    else:
        VIEWS.mkdir(exist_ok=True)
        for path, text in views.items():
            path.write_text(text)
    print(f"{len(elements)} elements, all well formed; views {'up to date' if args.check else 'written'}")


if __name__ == "__main__":
    main()
